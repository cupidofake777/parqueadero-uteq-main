  'REG-' || lpad(d.numero_fila::text, 3, '0'),
  d.id,
  p.id,
  d.placa,
  p.sensor_id_rtdb,
  case
    when d.numero_fila <= 20
      then now() - make_interval(hours => 1 + (d.numero_fila % 6))
    else now() - make_interval(days => 1 + (d.numero_fila % 12), hours => 3)
  end,
  case
    when d.numero_fila <= 20 then null
    else now() - make_interval(days => 1 + (d.numero_fila % 12))
  end,
  case when d.numero_fila <= 20 then null else 180 end,
  (28 + (d.numero_fila % 9) * 5)::numeric(6,2),
  case when d.numero_fila <= 20 then 'ACTIVO' else 'FINALIZADO' end,
  case
    when d.numero_fila <= 20 then 'Ingreso simulado; vehículo actualmente estacionado.'
    else 'Registro histórico simulado para fines académicos.'
  end
from datos_registro d
join public.puestos p on p.codigo = d.codigo_puesto
on conflict (codigo_registro) do update set
  vehiculo_id = excluded.vehiculo_id,
  puesto_id = excluded.puesto_id,
  placa_detectada = excluded.placa_detectada,
  sensor_id_rtdb = excluded.sensor_id_rtdb,
  fecha_entrada = excluded.fecha_entrada,
