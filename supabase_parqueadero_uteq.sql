with vehiculos_numerados as (
  select
    id,
    placa,
    row_number() over (order by id)::integer as numero_fila
  from public.vehiculos
  where cedula_propietario in (
    '1208595122','1207987460','1207440361','1250170212','1207856160',
    '0959406950','1207593383','1206883843','1250887013','1207700558',
    '1250094297','1250127568','1207244086','1251019715','1312593120',
    '1251239891','1206591248','1727183111','1206787630','1250566351',
    '1207664028','1207432970','1726035064','1208259349','1250108303',
    '1207038140','1206776500','0953240728','2300015910','1205285503',
    '0942146309','0940541196','2351049941','1250527734','2300560097',
    '1207295682','1250958533','1250165337'
  )
), datos_registro as (
  select
    v.*,
    (array['A','B','C','D'])[((v.numero_fila - 1) % 4) + 1]
      || lpad((((v.numero_fila - 1) / 4) + 1)::text, 2, '0') as codigo_puesto
  from vehiculos_numerados v
)
insert into public.registros_estacionamiento (
  codigo_registro,
  vehiculo_id,
  puesto_id,
  placa_detectada,
  sensor_id_rtdb,
  fecha_entrada,
  fecha_salida,
  duracion_minutos,
  distancia_cm_entrada,
  estado,
  observacion
)
