-- ----------------------------------------------------------------
-- 8. PANEL DE ADMINISTRACIÓN (CRUD) SOBRE VEHICULOS
-- Esta práctica amplía la anterior (solo lectura) para permitir que el
-- panel administrativo liste, cree, edite y elimine vehículos/propietarios
-- directamente desde el frontend con la clave "anon" de Supabase.
--
-- ADVERTENCIA (alcance académico): al no incluir autenticación de
-- usuarios, se habilita el CRUD completo también al rol "anon" para que
-- la práctica funcione sin backend propio. En un entorno productivo real
-- estas operaciones deben quedar detrás de Supabase Auth y una policy
-- que verifique auth.role() = 'authenticated' (o un claim de admin),
-- nunca abiertas a "anon".
-- ----------------------------------------------------------------

-- 8.1 Lectura: el panel administrativo necesita ver todas las columnas
-- (incluida la cédula completa, para poder precargarla en el formulario
-- de edición), a diferencia de la vista pública de solo lectura que
-- únicamente exponía la cédula enmascarada.
grant select, insert, update, delete on table public.vehiculos to anon, authenticated;

-- El id es identity (autogenerado) y no debe ser escrito por el cliente;
-- cedula_enmascarada y created_at son generadas/con default.
revoke update (id, cedula_enmascarada, created_at) on public.vehiculos from anon, authenticated;
revoke insert (id, cedula_enmascarada, created_at) on public.vehiculos from anon, authenticated;

drop policy if exists "Lectura publica de vehiculos autorizados" on public.vehiculos;
drop policy if exists "Panel admin: lectura total de vehiculos" on public.vehiculos;
drop policy if exists "Panel admin: crear vehiculos" on public.vehiculos;
drop policy if exists "Panel admin: editar vehiculos" on public.vehiculos;
drop policy if exists "Panel admin: eliminar vehiculos" on public.vehiculos;

-- 8.2 SELECT: el panel ve el listado completo (autorizados o no), para
-- poder administrar cualquier registro.
create policy "Panel admin: lectura total de vehiculos"
on public.vehiculos
for select
to anon, authenticated
using (true);

-- 8.3 INSERT: alta de un nuevo vehículo/propietario. Los checks de la
-- tabla (placa, cédula, año) ya validan el formato a nivel de base de
-- datos; aquí solo confirmamos que la fila insertada cumpla lo mismo.
create policy "Panel admin: crear vehiculos"
on public.vehiculos
for insert
to anon, authenticated
with check (
  placa ~ '^[A-Z]{3}-[0-9]{4}$'
  and cedula_propietario ~ '^[0-9]{10}$'
  and anio between 1990 and 2035
);

-- 8.4 UPDATE: edición de un vehículo/propietario existente.
create policy "Panel admin: editar vehiculos"
on public.vehiculos
for update
to anon, authenticated
using (true)
with check (
  placa ~ '^[A-Z]{3}-[0-9]{4}$'
  and cedula_propietario ~ '^[0-9]{10}$'
  and anio between 1990 and 2035
);

-- 8.5 DELETE: baja de un vehículo/propietario (con confirmación en el
-- frontend antes de ejecutar la petición).
create policy "Panel admin: eliminar vehiculos"
on public.vehiculos
for delete
to anon, authenticated
using (true);

commit;

