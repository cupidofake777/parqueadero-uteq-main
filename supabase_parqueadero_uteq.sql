begin;

-- ----------------------------------------------------------------
-- 1. TABLA VEHICULOS
-- Una sola tabla reúne el vehículo y los datos de su propietario.
-- ----------------------------------------------------------------
create table if not exists public.vehiculos (
  id bigint generated by default as identity primary key,
  placa varchar(8) not null unique,
  marca text not null,
  modelo text not null,
  anio smallint not null check (anio between 1990 and 2035),
  color text not null,
  tipo text not null default 'AUTOMOVIL'
    check (tipo in ('AUTOMOVIL', 'CAMIONETA', 'SUV', 'MOTOCICLETA')),
  foto_url text not null,
  foto_fuente_url text not null,
  foto_propietario_url text not null,
  cedula_propietario varchar(10) not null unique,
  cedula_enmascarada text generated always as
    ('******' || right(cedula_propietario, 4)) stored,
  propietario_nombre text not null,
  correo_institucional text not null,
  correo_microsoft text,
  autorizado boolean not null default true,
  created_at timestamptz not null default now(),
  constraint vehiculos_placa_ecuador_chk
    check (placa ~ '^[A-Z]{3}-[0-9]{4}$'),
  constraint vehiculos_cedula_chk
    check (cedula_propietario ~ '^[0-9]{10}$')
);

-- Permite volver a ejecutar esta versión sobre una tabla creada con una
-- versión anterior del script que todavía no tenía la foto del propietario.
alter table public.vehiculos
  add column if not exists foto_propietario_url text;

create index if not exists idx_vehiculos_propietario
  on public.vehiculos (propietario_nombre);

create index if not exists idx_vehiculos_marca_modelo
  on public.vehiculos (marca, modelo);

-- ----------------------------------------------------------------
-- 2. TABLA PUESTOS
-- Distribución visual: cuatro columnas (A, B, C y D), 20 puestos
-- por columna. sensor_id_rtdb coincide con el nodo usado en Firebase.
-- ----------------------------------------------------------------
create table if not exists public.puestos (
  id smallint generated by default as identity primary key,
  codigo varchar(3) not null unique,
  columna char(1) not null check (columna in ('A', 'B', 'C', 'D')),
  numero smallint not null check (numero between 1 and 20),
  sensor_id_rtdb text not null unique,
  ruta_firebase text not null unique,
  estado text not null default 'DISPONIBLE'
    check (estado in ('DISPONIBLE', 'OCUPADO', 'RESERVADO', 'FUERA_SERVICIO')),
  distancia_cm numeric(6,2),
  ultima_actualizacion timestamptz,
  created_at timestamptz not null default now(),
  unique (columna, numero)
);

create index if not exists idx_puestos_estado
  on public.puestos (estado);

-- ----------------------------------------------------------------
-- 3. TABLA REGISTROS_ESTACIONAMIENTO
-- Preparada para recibir en el futuro eventos del detector de placas
-- y de los sensores. En esta práctica no se visualiza esta tabla.
-- ----------------------------------------------------------------
create table if not exists public.registros_estacionamiento (
  id bigint generated by default as identity primary key,
  codigo_registro varchar(12) not null unique,
  vehiculo_id bigint not null
    references public.vehiculos(id) on update cascade on delete restrict,
  puesto_id smallint not null
    references public.puestos(id) on update cascade on delete restrict,
  placa_detectada varchar(8) not null,
  sensor_id_rtdb text not null,
  fecha_entrada timestamptz not null,
  fecha_salida timestamptz,
  duracion_minutos integer check (duracion_minutos is null or duracion_minutos >= 0),
  distancia_cm_entrada numeric(6,2),
  estado text not null default 'ACTIVO'
    check (estado in ('ACTIVO', 'FINALIZADO', 'ANULADO')),
  observacion text,
  created_at timestamptz not null default now(),
  constraint registros_fechas_chk
    check (fecha_salida is null or fecha_salida >= fecha_entrada),
  constraint registros_salida_estado_chk
    check (
      (estado = 'ACTIVO' and fecha_salida is null)
      or (estado in ('FINALIZADO', 'ANULADO') and fecha_salida is not null)
    )
);

create index if not exists idx_registros_vehiculo
  on public.registros_estacionamiento (vehiculo_id);

create index if not exists idx_registros_puesto
  on public.registros_estacionamiento (puesto_id);

create index if not exists idx_registros_fecha_entrada
  on public.registros_estacionamiento (fecha_entrada desc);

-- Solo puede existir un uso activo por vehículo y por puesto.
create unique index if not exists uq_registro_activo_vehiculo
  on public.registros_estacionamiento (vehiculo_id)
  where estado = 'ACTIVO';

create unique index if not exists uq_registro_activo_puesto
  on public.registros_estacionamiento (puesto_id)
  where estado = 'ACTIVO';

