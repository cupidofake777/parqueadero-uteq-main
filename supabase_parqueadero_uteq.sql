-- ----------------------------------------------------------------
-- 5. CARGA DE LOS 80 PUESTOS: A01-D20
-- Ejemplos de nodos RTDB:
--   parking_A_01 -> /parqueadero/sensores/parking_A_01
--   parking_D_20 -> /parqueadero/sensores/parking_D_20
-- Los primeros cinco puestos de cada columna quedan ocupados para
-- representar 20 vehículos actualmente dentro del estacionamiento.
-- ----------------------------------------------------------------
insert into public.puestos (
  codigo,
  columna,
  numero,
  sensor_id_rtdb,
  ruta_firebase,
  estado,
  distancia_cm,
  ultima_actualizacion
)
select
  columna || lpad(numero::text, 2, '0') as codigo,
  columna,
  numero,
  'parking_' || columna || '_' || lpad(numero::text, 2, '0') as sensor_id_rtdb,
  '/parqueadero/sensores/parking_' || columna || '_' || lpad(numero::text, 2, '0') as ruta_firebase,
  case when numero <= 5 then 'OCUPADO' else 'DISPONIBLE' end as estado,
  case
    when numero <= 5 then (25 + numero * 6 + posicion * 3)::numeric(6,2)
    else (145 + numero * 5 + posicion * 7)::numeric(6,2)
  end as distancia_cm,
  -- WITH ORDINALITY devuelve posicion como bigint; make_interval exige integer.
  now() - make_interval(mins => (numero + posicion)::integer) as ultima_actualizacion
from unnest(array['A', 'B', 'C', 'D']) with ordinality as c(columna, posicion)
cross join generate_series(1, 20) as n(numero)
on conflict (codigo) do update set
  sensor_id_rtdb = excluded.sensor_id_rtdb,
  ruta_firebase = excluded.ruta_firebase,
  estado = excluded.estado,
  distancia_cm = excluded.distancia_cm,
  ultima_actualizacion = excluded.ultima_actualizacion;

